# -*- coding: utf-8 -*-
"""tools/build_allowlist.py: build a known-clean allowlist, then prove the
scanner honours it - a whitelisted clean file is suppressed, a planted
backdoor (not in the list) is still flagged.

Black-box like the rest of the suite: the tool and the scanner each run as a
separate python process, exactly as a user would invoke them.
"""

import os
import subprocess
import unittest

import harness as H
import fixtures_sites as fx

TOOL = os.path.join(H.REPO, "tools", "build_allowlist.py")


def run_tool(args, timeout=600):
    """Run tools/build_allowlist.py -> (returncode, combined output)."""
    proc = subprocess.Popen(
        [H.PYTHON, "-u", TOOL] + [str(a) for a in args],
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
        universal_newlines=True, encoding="utf-8", errors="replace", env=H.ENV)
    try:
        out, _ = proc.communicate(timeout=timeout)
    except Exception:
        proc.kill()
        out, _ = proc.communicate()
        raise
    return proc.returncode, out or ""


def read_entries(path):
    """Non-comment, non-blank lines of an allowlist file."""
    with open(path, encoding="utf-8") as f:
        return [ln.strip() for ln in f if ln.strip() and not ln.startswith("#")]


class BuildAllowlistTest(unittest.TestCase):
    def _build(self, site, fmt, out, *extra):
        rc, outp = run_tool([site, "--format", fmt, "--out", out] + list(extra))
        self.assertEqual(rc, 0, "build_allowlist failed:\n%s" % outp)
        self.assertTrue(os.path.isfile(out), "no allowlist file was written")
        return outp

    def test_header_and_hashes(self):
        site = fx.build("al-a", planted=False)
        out = os.path.join(H.workdir("al-a"), "wl.txt")
        self._build(site, "hashes", out)
        with open(out, encoding="utf-8") as f:
            raw = f.read()
        self.assertIn("generated by build_allowlist", raw)
        self.assertIn("from %s" % site, raw)
        entries = read_entries(out)
        n_files = sum(len(fs) for _r, _d, fs in os.walk(site))
        self.assertEqual(len(entries), n_files,
                         "expected %d entries, got %d" % (n_files, len(entries)))
        for ln in entries:
            self.assertEqual(len(ln.split("#")[0].strip()), 64,
                             "line is not a 64-hex SHA-256: %r" % ln)

    def test_suppresses_flagged_clean_file(self):
        # a legitimate file that the scanner still reports (a custom X- header,
        # OBFUSCATED): whitelisting it must silence the finding.
        site = fx.build("al-b", planted=False, extra={
            "scripts/notify.php": "<?php\nheader('X-Custom-Info: 1');\necho 'ok';\n"})
        out = os.path.join(H.workdir("al-b"), "wl.txt")
        self._build(site, "hashes", out)

        _res, rep_no = H.scan(site)
        self.assertIn("scripts/notify.php", H.findings_by_path(rep_no),
                      "precondition: the X-header file should be flagged WITHOUT the allowlist")

        _res, rep_yes = H.scan(site, "--whitelist", out)
        self.assertNotIn("scripts/notify.php", H.findings_by_path(rep_yes),
                         "the allowlist did not suppress a whitelisted clean file")

    def test_planted_still_flagged(self):
        clean = fx.build("al-c", planted=False)
        out = os.path.join(H.workdir("al-c"), "wl.txt")
        self._build(clean, "hashes", out)

        planted = fx.build("al-c-planted", planted=True)
        present, _vanished = fx.wait_readables(planted, list(fx.PLANTED))
        if len(present) < 3:
            raise unittest.SkipTest("too few planted samples survived: %s" % H.AV_HINT)

        _res, rep = H.scan(planted, "--whitelist", out)
        flagged = H.findings_by_path(rep)
        self.assertIn("tmp/media_view.php", flagged,
                      "the planted backdoor was NOT flagged despite the allowlist: %s"
                      % sorted(flagged))
        self.assertEqual(flagged["tmp/media_view.php"]["verdict"], "HIGH")
        # a byte-identical clean file (same hash) stays suppressed
        self.assertNotIn("index.php", flagged,
                         "identical clean index.php was flagged despite the allowlist")

    def test_paths_format(self):
        site = fx.build("al-d", planted=False)
        out = os.path.join(H.workdir("al-d"), "wl.txt")
        self._build(site, "paths", out)
        entries = read_entries(out)
        self.assertIn("index.php", entries)
        self.assertIn("templates/protostar/js/template.js", entries)

    def test_stdout_default(self):
        site = fx.build("al-e", planted=False)
        rc, outp = run_tool([site, "--format", "paths"])   # no --out -> stdout
        self.assertEqual(rc, 0, outp)
        self.assertIn("generated by build_allowlist", outp)
        self.assertIn("index.php", outp)


if __name__ == "__main__":
    unittest.main()
